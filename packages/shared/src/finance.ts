import { z } from 'zod';
import { isoDate, optionalText } from './primitives';

/**
 * Money crosses the API as decimal strings ("65596", "100.50") — never JS floats (§6.5).
 * Decimals beyond the currency's minor units (XAF: 0, EUR: 2) are rejected by the API.
 */
export const money = z
  .string()
  .trim()
  .regex(/^\d{1,13}(\.\d{1,2})?$/, 'invalid_amount')
  .refine((v) => /[1-9]/.test(v), 'amount_not_positive');
export const moneyOrZero = z.string().trim().regex(/^\d{1,13}(\.\d{1,2})?$/, 'invalid_amount');
/** "1 base = rate quote", up to 10 decimals. */
export const rateValue = z
  .string()
  .trim()
  .regex(/^\d{1,10}(\.\d{1,10})?$/, 'invalid_rate')
  .refine((v) => /[1-9]/.test(v), 'rate_not_positive');
export const currencyCode = z.string().trim().toUpperCase().regex(/^[A-Z]{3}$/, 'invalid_currency');

export const FEE_KINDS = ['REGISTRATION', 'TUITION', 'EXAM', 'TRANSPORT', 'CANTEEN', 'UNIFORM', 'OTHER'] as const;
export const DISCOUNT_KINDS = ['DISCOUNT', 'SCHOLARSHIP', 'WAIVER'] as const;
export const PAYMENT_METHODS = ['CASH', 'BANK_TRANSFER', 'CARD', 'MOBILE_MONEY', 'CHEQUE'] as const;
export type PaymentMethod = (typeof PAYMENT_METHODS)[number];

export const financeSettingsSchema = z.object({
  enabledCurrencies: z.array(currencyCode).min(1).max(10),
  expenseApprovalThreshold: moneyOrZero,
});
export type FinanceSettingsInput = z.infer<typeof financeSettingsSchema>;

export const exchangeRateSchema = z
  .object({ baseCurrency: currencyCode, quoteCurrency: currencyCode, rate: rateValue, effectiveDate: isoDate })
  .refine((v) => v.baseCurrency !== v.quoteCurrency, { message: 'same_currency', path: ['quoteCurrency'] });
export type ExchangeRateInput = z.infer<typeof exchangeRateSchema>;

export const financialPeriodSchema = z
  .object({ name: z.string().trim().min(2).max(60), startDate: isoDate, endDate: isoDate })
  .refine((v) => v.endDate >= v.startDate, { message: 'end_before_start', path: ['endDate'] });
export type FinancialPeriodInput = z.infer<typeof financialPeriodSchema>;

const code = z.string().trim().min(1).max(20).regex(/^[A-Za-z0-9._-]+$/, 'invalid_code');
const label = z.string().trim().min(1).max(120);

export const feeCategorySchema = z.object({ code, nameFr: label, nameEn: label, kind: z.enum(FEE_KINDS) });
export type FeeCategoryInput = z.infer<typeof feeCategorySchema>;

export const feeScheduleSchema = z
  .object({
    academicYearId: z.uuid(),
    categoryId: z.uuid(),
    name: label,
    currency: currencyCode,
    /** Limit to a level or a class; neither means every enrollment of the year. */
    levelId: z.uuid().optional(),
    classId: z.uuid().optional(),
    installments: z
      .array(z.object({ label: z.string().trim().min(1).max(60), dueDate: isoDate, amount: money }))
      .min(1)
      .max(12),
  })
  .refine((v) => !(v.levelId && v.classId), { message: 'single_scope', path: ['classId'] })
  .refine((v) => v.installments.every((i, n, all) => n === 0 || all[n - 1]!.dueDate <= i.dueDate), {
    message: 'installments_out_of_order',
    path: ['installments'],
  });
export type FeeScheduleInput = z.infer<typeof feeScheduleSchema>;

export const applyScheduleSchema = z.object({ issueDate: isoDate });
export type ApplyScheduleInput = z.infer<typeof applyScheduleSchema>;

export const discountSchema = z.object({
  kind: z.enum(DISCOUNT_KINDS),
  amount: money,
  reason: z.string().trim().min(3).max(300),
});
export type DiscountInput = z.infer<typeof discountSchema>;

export const reasonSchema = z.object({ reason: z.string().trim().min(3).max(500) });
export type ReasonInput = z.infer<typeof reasonSchema>;

/**
 * Recording a payment. `idempotencyKey` is generated by the client once per payment
 * attempt and reused on retries, so a double click or a resend never records twice (FIN-010).
 * Without `allocations`, the payment settles the student's oldest dues first.
 */
export const paymentSchema = z.object({
  idempotencyKey: z.uuid(),
  studentId: z.uuid(),
  method: z.enum(PAYMENT_METHODS),
  currency: currencyCode,
  amount: money,
  receivedOn: isoDate,
  externalReference: z.string().trim().min(2).max(80).optional(),
  /** Mobile Money / provider payments start pending until the provider confirms. */
  provider: z.string().trim().min(2).max(30).optional(),
  /** Payer's Mobile Money number, international format without '+' (e.g. 2376XXXXXXXX). */
  payerMsisdn: z.string().trim().regex(/^\d{9,15}$/, 'invalid_msisdn').optional(),
  allocations: z.array(z.object({ invoiceId: z.uuid(), amount: money })).max(20).optional(),
  notes: optionalText(300),
});
export type PaymentInput = z.infer<typeof paymentSchema>;

export const refundRequestSchema = z.object({ amount: money, reason: z.string().trim().min(3).max(500) });
export type RefundRequestInput = z.infer<typeof refundRequestSchema>;

export const refundDecisionSchema = z.object({ approve: z.boolean(), note: optionalText(500) });
export type RefundDecisionInput = z.infer<typeof refundDecisionSchema>;

export const cashierOpenSchema = z.object({ currency: currencyCode, openingFloat: moneyOrZero });
export type CashierOpenInput = z.infer<typeof cashierOpenSchema>;

export const cashierCloseSchema = z.object({ countedAmount: moneyOrZero, notes: optionalText(500) });
export type CashierCloseInput = z.infer<typeof cashierCloseSchema>;

const providerCode = z.string().trim().toLowerCase().regex(/^[a-z0-9_-]{2,30}$/, 'invalid_code');
const credential = z.string().trim().min(1).max(200);

export const PROVIDER_KINDS = ['SIGNED_WEBHOOK', 'MTN_MOMO', 'ORANGE_MONEY'] as const;
export type ProviderKind = (typeof PROVIDER_KINDS)[number];

/**
 * A school's payment provider. SIGNED_WEBHOOK: an aggregator that posts HMAC-signed results.
 * MTN_MOMO / ORANGE_MONEY: the operators' collection APIs; Mboka starts the payment and always
 * asks the operator for the result (their notifications are not signed, so they are only a hint).
 * Credentials are encrypted at rest and never returned.
 */
const providerConfigUnion = z.discriminatedUnion('kind', [
  z.object({ kind: z.literal('SIGNED_WEBHOOK'), code: providerCode, secret: z.string().min(16).max(200) }),
  z.object({
    kind: z.literal('MTN_MOMO'),
    code: providerCode,
    baseUrl: z.url(),
    /** X-Target-Environment: `sandbox`, or the production value MTN assigns (e.g. `mtncameroon`). */
    targetEnvironment: z.string().trim().regex(/^[a-z0-9]{3,30}$/),
    subscriptionKey: credential,
    apiUser: credential,
    apiKey: credential,
  }),
  z.object({
    kind: z.literal('ORANGE_MONEY'),
    code: providerCode,
    baseUrl: z.url(),
    clientId: credential,
    clientSecret: credential,
    merchantKey: credential,
    /** Where the payer's browser returns after paying on Orange's page. */
    returnUrl: z.url(),
  }),
]);
/** Bodies without `kind` are the original signed-webhook configuration. */
export const providerConfigSchema = z.preprocess(
  (v) => (v && typeof v === 'object' && !('kind' in v) ? { ...v, kind: 'SIGNED_WEBHOOK' } : v),
  providerConfigUnion,
);
export type ProviderConfigInput = z.infer<typeof providerConfigSchema>;

/** Body a payment provider posts to the callback URL, signed with HMAC-SHA256 (X-Mboka-Signature). */
export const providerCallbackSchema = z.object({
  transactionId: z.string().trim().min(1).max(100),
  status: z.enum(['SUCCESS', 'FAILED', 'PENDING']),
  amount: money,
  currency: currencyCode,
  /** The payment's idempotency key, sent to the provider when the payment was initiated. */
  reference: z.uuid(),
});
export type ProviderCallbackInput = z.infer<typeof providerCallbackSchema>;

export const expenseCategorySchema = z.object({ code, nameFr: label, nameEn: label });
export type ExpenseCategoryInput = z.infer<typeof expenseCategorySchema>;

export const expenseSchema = z.object({
  categoryId: z.uuid(),
  supplier: optionalText(120),
  description: z.string().trim().min(3).max(300),
  amount: money,
  currency: currencyCode,
  expenseDate: isoDate,
});
export type ExpenseInput = z.infer<typeof expenseSchema>;

export const EXPENSE_ACTIONS = ['APPROVE', 'REJECT', 'PAY', 'CANCEL'] as const;
export const expenseActionSchema = z.object({
  action: z.enum(EXPENSE_ACTIONS),
  comment: optionalText(500),
  paymentReference: z.string().trim().max(80).optional(),
});
export type ExpenseActionInput = z.infer<typeof expenseActionSchema>;

export const budgetSchema = z.object({
  academicYearId: z.uuid(),
  name: label,
  lines: z.array(z.object({ categoryId: z.uuid(), amount: moneyOrZero })).min(1).max(100),
});
export type BudgetInput = z.infer<typeof budgetSchema>;

export const reportRangeSchema = z
  .object({ from: isoDate, to: isoDate })
  .refine((v) => v.to >= v.from, { message: 'end_before_start', path: ['to'] });
export type ReportRange = z.infer<typeof reportRangeSchema>;
